def load_issues(path: str | Path) -> list[dict[str, Any]]:
    """
    Load and validate the issues JSON file.

    Raises
    ------
    FileNotFoundError  if the file does not exist.
    ValueError         if the file is not a JSON array, or if it is empty.
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Issues file not found: {path}")
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, list):
        raise ValueError(
            f"Expected a JSON array in {path}, got {type(data).__name__}"
        )
    if len(data) == 0:
        raise ValueError(f"Issues file is empty — nothing to audit: {path}")
    return data


def load_metadata(path: str | Path) -> dict[str, Any]:
    """Load the collection metadata JSON file."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Metadata file not found: {path}")
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


