def compute_missing_data(issues: list[dict]) -> dict[str, int]:
    """
    Count issues with missing (None) or empty (whitespace-only) fields.

    Returns a dict with separate counts for title and body problems.
    """
    missing_title = empty_title = 0
    missing_body = empty_body = 0

    for issue in issues:
        title = issue.get("title")
        body = issue.get("body")

        if title is None:
            missing_title += 1
        elif not str(title).strip():
            empty_title += 1

        if body is None:
            missing_body += 1
        elif not str(body).strip():
            empty_body += 1

    return {
        "missing_title": missing_title,
        "empty_title": empty_title,
        "missing_body": missing_body,
        "empty_body": empty_body,
        "total_title_problems": missing_title + empty_title,
        "total_body_problems": missing_body + empty_body,
    }


def compute_text_lengths(issues: list[dict]) -> dict[str, list[int]]:
    """
    Compute character lengths for title, body, and their concatenation.

    Missing / None values are treated as empty strings (length 0).
    Trailing whitespace is stripped before measuring.
    """
    title_lengths, body_lengths, combined_lengths = [], [], []

    for issue in issues:
        title = str(issue.get("title") or "").strip()
        body = str(issue.get("body") or "").strip()
        title_lengths.append(len(title))
        body_lengths.append(len(body))
        combined_lengths.append(len(title) + len(body))

    return {
        "title": title_lengths,
        "body": body_lengths,
        "combined": combined_lengths,
    }


def describe_lengths(lengths: list[int]) -> dict[str, float]:
    """
    Return descriptive statistics for a list of integer lengths.
    Requires numpy — only call from environments where numpy is available.
    """
    import numpy as np  # lazy import: numpy is not a dep of pure audit logic

    arr = np.array(lengths, dtype=float)
    return {
        "min": float(np.min(arr)),
        "max": float(np.max(arr)),
        "mean": float(np.mean(arr)),
        "median": float(np.median(arr)),
        "p25": float(np.percentile(arr, 25)),
        "p75": float(np.percentile(arr, 75)),
        "p95": float(np.percentile(arr, 95)),
    }


# ---------------------------------------------------------------------------
# State and temporal distributions
# ---------------------------------------------------------------------------


def compute_state_distribution(issues: list[dict]) -> Counter:
    """Count issues by state ('open' or 'closed')."""
    return Counter(issue.get("state", "unknown") for issue in issues)


def compute_temporal_distribution(issues: list[dict]) -> Counter:
    """
    Count issues by year-month of creation.

    Returns a Counter keyed by 'YYYY-MM' strings, sorted chronologically.
    """
    monthly: Counter = Counter()
    for issue in issues:
        ts = issue.get("created_at")
        if ts:
            try:
                dt = datetime.fromisoformat(ts.replace("Z", "+00:00"))
                monthly[dt.strftime("%Y-%m")] += 1
            except ValueError:
                pass
    return monthly


# ---------------------------------------------------------------------------
# Leakage detection
# ---------------------------------------------------------------------------


def detect_leakage(
    issues: list[dict],
    type_labels: frozenset[str] | None = None,
    prefixes: list[str] | None = None,
) -> dict[str, list[int]]:
    """
    Check issue titles for patterns that might cause label leakage.

    Two checks are performed:

    1. Prefix check — does the title begin with a known category prefix
       such as "[BUG]", "ENH:", "RFC" etc.?
    2. Label-in-title check — does the title contain a type label name
       literally (e.g. the word "bug" in a Bug-labelled issue)?

    Returns
    -------
    A dict mapping check name → list of issue numbers that triggered it.
    """
    if type_labels is None:
        type_labels = PROVISIONAL_TYPE_LABELS
    if prefixes is None:
        prefixes = LEAKAGE_PREFIXES

    # Pattern: optional whitespace, optional [ or (, then prefix, then
    # ] or ) or : or whitespace — at the very start of the string.
    prefix_pattern = re.compile(
        r"^\s*[\[\(]?("
        + "|".join(re.escape(p) for p in prefixes)
        + r")[\]\):\s]",
        re.IGNORECASE,
    )

    prefix_matches: list[int] = []
    label_in_title: list[int] = []

    for issue in issues:
        number = issue.get("number", -1)
        title = str(issue.get("title") or "")
        title_lower = title.lower()

        if prefix_pattern.match(title):
            prefix_matches.append(number)

        # Check if any type label name appears literally in the title
        for label in type_labels:
            if label.lower() in title_lower:
                label_in_title.append(number)
                break

    return {
        "prefix_matches": prefix_matches,
        "label_in_title": label_in_title,
    }


# ---------------------------------------------------------------------------
# Provisional type-label subset
# ---------------------------------------------------------------------------


def build_provisional_subset(
    issues: list[dict],
    type_labels: frozenset[str] | None = None,
) -> dict[str, Any]:
    """
    Build the provisional single-type-label subset.

    Rules
    -----
    - An issue must have exactly ONE provisional type label to be included.
    - Issues with zero type labels are excluded (unlabelled for our task).
    - Issues with two or more type labels are excluded (ambiguous).

    Returns
    -------
    A dict containing:
    subset           : list of (issue_dict, assigned_label) pairs
    class_counts     : Counter of label → count in the subset
    excluded_unlabelled : count excluded for having no type label
    excluded_multi_type : count excluded for having multiple type labels
    total_usable     : len(subset)
    type_label_overlap : list of (issue_number, matched_labels) for multi-type issues
    """
    if type_labels is None:
        type_labels = PROVISIONAL_TYPE_LABELS

    subset: list[tuple[dict, str]] = []
    excluded_unlabelled = 0
    excluded_multi_type = 0
    type_label_overlap: list[tuple[int, list[str]]] = []

    for issue in issues:
        issue_labels = set(issue.get("labels") or [])
        type_matches = issue_labels & type_labels

        if len(type_matches) == 0:
            excluded_unlabelled += 1
        elif len(type_matches) > 1:
            excluded_multi_type += 1
            type_label_overlap.append(
                (issue.get("number", -1), sorted(type_matches))
            )
        else:
            assigned = next(iter(type_matches))
            subset.append((issue, assigned))

    class_counts: Counter = Counter(label for _, label in subset)

    return {
        "subset": subset,
        "class_counts": class_counts,
        "excluded_unlabelled": excluded_unlabelled,
        "excluded_multi_type": excluded_multi_type,
        "total_usable": len(subset),
        "type_label_overlap": type_label_overlap,
    }
