# These five are our candidate issue-type prediction classes.
# They will be finalised after the Stage 1B audit.
PROVISIONAL_TYPE_LABELS: frozenset[str] = frozenset(
    ["Bug", "Documentation", "New Feature", "RFC", "Build / CI"]
)

# Prefixes that may indicate the category has leaked into the title.
LEAKAGE_PREFIXES: list[str] = [
    "BUG", "DOC", "ENH", "FEATURE", "RFC", "CI", "FIX", "MAINT", "TST",
]


