def compute_label_frequencies(issues: list[dict]) -> Counter:
    """Return a Counter mapping each label name to its occurrence count."""
    counter: Counter = Counter()
    for issue in issues:
        for label in issue.get("labels") or []:
            counter[label] += 1
    return counter


def compute_labels_per_issue(issues: list[dict]) -> list[int]:
    """Return a list of label counts, one per issue (0 if unlabelled)."""
    return [len(issue.get("labels") or []) for issue in issues]


def compute_label_cooccurrence(
    issues: list[dict],
    selected_labels: list[str] | None = None,
) -> dict[tuple[str, str], int]:
    """
    Count how often pairs of labels appear together on the same issue.

    If selected_labels is given, only pairs where both labels are in
    that set are counted.  Otherwise all labels are included.

    Returns
    -------
    A dict mapping (label_a, label_b) → count, where label_a < label_b
    lexicographically (each pair is stored once).
    """
    cooc: dict[tuple[str, str], int] = defaultdict(int)
    for issue in issues:
        labels = list(issue.get("labels") or [])
        if selected_labels is not None:
            labels = [lb for lb in labels if lb in selected_labels]
        for i in range(len(labels)):
            for j in range(i + 1, len(labels)):
                pair: tuple[str, str] = tuple(sorted([labels[i], labels[j]]))  # type: ignore[assignment]
                cooc[pair] += 1
    return dict(cooc)


def categorize_labels_provisionally(
    label_freq: Counter,
) -> dict[str, list[str]]:
    """
    Provisionally group observed labels into four roles.

    IMPORTANT: This grouping is manually proposed based on the 500-issue
    sample only.  It must be treated as provisional and will be revised
    after a broader collection.

    Categories
    ----------
    type       — What kind of issue this is (prediction target).
    component  — Which part of the codebase is affected.
    workflow   — Current triage or process state.
    lifecycle  — Administrative / housekeeping labels.
    other      — Labels not yet classified.
    """
    type_labels = ["Bug", "Documentation", "New Feature", "RFC", "Build / CI"]
    component_labels = [
        "Array API", "Callbacks", "module:test-suite", "free-threading",
        "frontend", "API", "module:linear_model",
    ]
    workflow_labels = [
        "Needs Triage", "Needs Decision", "Needs Investigation",
        "Needs Info", "Needs Decision - Include Feature",
    ]
    lifecycle_labels = ["Closing candidate", "spam", "Sprint"]

    known = set(
        type_labels + component_labels + workflow_labels + lifecycle_labels
    )
    other = [lb for lb in label_freq if lb not in known]

    return {
        "type": type_labels,
        "component": component_labels,
        "workflow": workflow_labels,
        "lifecycle": lifecycle_labels,
        "other": sorted(other),
    }


